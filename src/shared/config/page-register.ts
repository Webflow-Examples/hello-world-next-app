// The page register. Transcribed once, at project start, from
// docs/Compremium_Estimate_SEO_Localisation_Social (final).xlsx, sheet 'Page & Metadata
// Register'. The transcription was a one-off; this file is now maintained by hand and the
// spreadsheet is provenance, not a build input.
//
// Every URL, template and gate in here is a reviewed value. Changing one is a specification
// change: it goes through docs/spec/page-register.md and claims review, not through a text
// edit here. See docs/spec/claims-guardrails.md.
//
// H1, title tag and meta description are deliberately NOT held here. They are drafted claim
// surfaces. The `page` field is an internal label for identifying a row and must never be
// rendered.

export type Silo = 'root' | 'A' | 'B' | 'C' | 'D' | 'E';

export type Template =
  | 'application-hub'
  | 'clinical-question'
  | 'conversion'
  | 'conversion-hub'
  | 'corporate-home'
  | 'entity'
  | 'evidence-item'
  | 'hub'
  | 'legal'
  | 'listing'
  | 'news'
  | 'person'
  | 'platform-hub'
  | 'platform-pillar'
  | 'product-hub'
  | 'provenance'
  | 'research-horizon-item'
  | 'reserved'
  | 'silo-hub'
  | 'spec'
  | 'spoke'
  | 'trust'
  | 'workflow';

export type Indexation =
  | 'Index, follow'
  | 'Index, follow after review'
  | 'Index, nofollow'
  | 'Noindex until rebuilt'
  | 'Not built';

export type ClaimsGate = 'HARD' | 'LOW' | 'MEDIUM';

export type Timing = 'GATED' | 'LATER' | 'NEXT' | 'NOW';

export interface RegisterEntry {
  readonly id: string;
  readonly silo: Silo;
  /** Internal label from the register. Never render this. */
  readonly page: string;
  /** One entry can own several URLs, e.g. the two legal pages. */
  readonly urls: readonly string[];
  /** The register wrote '.../slug'; the parent path is unresolved. */
  readonly urlUnresolved: boolean;
  readonly template: Template;
  /** schema.org mapping, verbatim from the register. */
  readonly schema: string;
  readonly indexation: Indexation;
  readonly gate: ClaimsGate;
  readonly timing: Timing;
  /** Locale availability, verbatim from the register. */
  readonly localeScope: string;
}

